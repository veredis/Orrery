// Generates THIRD-PARTY-LICENSES.txt from what ships in the app: "dependencies" (packed by
// electron-builder for the main process) plus "bundledInApp" (compiled into the web bundle by Vite).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const pkg = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const seen = new Map();

function resolveDir(name, fromDir) {
    let dir = fromDir;
    for (;;) {
        const cand = path.join(dir, "node_modules", name);
        if (fs.existsSync(path.join(cand, "package.json"))) return cand;
        const up = path.dirname(dir);
        if (up === dir) return null;
        dir = up;
    }
}

function walk(name, fromDir) {
    const dir = resolveDir(name, fromDir);
    if (!dir) return;
    const p = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
    const key = `${p.name}@${p.version}`;
    if (seen.has(key)) return;
    const licFile = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\..*)?$/i.test(f));
    seen.set(key, {
        name: p.name,
        version: p.version,
        license: typeof p.license === "string" ? p.license : p.license?.type ?? (p.licenses ?? []).map((l) => l.type).join(" OR ") ?? "UNKNOWN",
        repo: typeof p.repository === "string" ? p.repository : p.repository?.url,
        text: licFile ? fs.readFileSync(path.join(dir, licFile), "utf8").trim() : null,
    });
    for (const dep of Object.keys({ ...p.dependencies, ...p.optionalDependencies })) walk(dep, dir);
}

for (const dep of [...Object.keys(pkg.dependencies ?? {}), ...(pkg.bundledInApp ?? [])]) walk(dep, root);

const entries = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
let out = `Orrery ${pkg.version} — third-party software notices\n`;
out += `Generated by scripts/third-party-licenses.mjs from the production dependency tree.\n\n`;
out += `Bundled data (not npm packages):\n`;
out += `  - OpenAI Whisper speech models (base.en, tiny.en), MIT License, Copyright (c) 2022 OpenAI.\n`;
out += `    ONNX conversions from https://huggingface.co/onnx-community (see each model card).\n`;
out += `  - ONNX Runtime Web (wasm), MIT License, Copyright (c) Microsoft Corporation.\n`;
out += `  - Electron and Chromium (desktop build only); their notices ship as LICENSE.electron.txt and\n`;
out += `    LICENSES.chromium.html next to the executable.\n\n`;
out += `Summary (${entries.length} packages):\n`;
for (const e of entries) out += `  ${e.name}@${e.version}  ${e.license}\n`;
for (const e of entries) {
    out += `\n${"=".repeat(78)}\n${e.name}@${e.version}  (${e.license})${e.repo ? `\n${e.repo}` : ""}\n${"-".repeat(78)}\n`;
    out += e.text ?? "(no license file shipped in the package; see the license field above)";
    out += "\n";
}
fs.writeFileSync(path.join(root, "THIRD-PARTY-LICENSES.txt"), out);
console.log(`wrote THIRD-PARTY-LICENSES.txt (${entries.length} packages)`);
